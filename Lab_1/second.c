#include <stdio.h>
#include <windows.h> // Бібліотека для налаштування кодування консолі Windows

int main() {
    // Встановлюємо кодування UTF-8 для вводу та виводу в консолі
    SetConsoleCP(65001);
    SetConsoleOutputCP(65001);

    double x, y;

    printf("Введіть значення x: ");
    if (scanf("%lf", &x) == 1) {

        // Перевірка проміжків D1 з використанням логічних операторів
        if ((x >= -49 && x < -10) || (x > 0 && x <= 10)) {
            // Виправлено пропущені знаки множення '*'
            y = 10 * x * x * x + (7.0 * x) / 5.0 + 2;
            printf("y(x) = %.2lf\n", y);
        }
        // Перевірка проміжку D2
        else if (x > 20) {
            y = -x + 9;
            printf("y(x) = %.2lf\n", y);
        }
        // Якщо x поза межами D1 та D2
        else {
            printf("Функція не визначена для x = %.2lf\n", x);
        }

    } else {
        printf("Помилка вводу!\n");
    }

    return 0;
}